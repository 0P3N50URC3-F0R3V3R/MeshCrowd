// Aggregated view over every curated category, de-duplicated — lets the picker offer a single
// "All" tab instead of forcing users to hunt through each category.
export const ALL_EMOJI_CATEGORY = {
  id: 'all', label: 'All Emoji', icon: '🔠',
  emoji: [...new Set(EMOJI_CATEGORIES.flatMap((cat) => cat.emoji))],
};
EMOJI_CATEGORIES.unshift(ALL_EMOJI_CATEGORY);

export function findEmojiCategory(query) {
  const q = query.trim().toLowerCase();
  if (!q) return EMOJI_CATEGORIES;
  return EMOJI_CATEGORIES
    .map((cat) => ({ ...cat, label: cat.label, emoji: cat.emoji }))
    .filter((cat) => cat.label.toLowerCase().includes(q));
}
