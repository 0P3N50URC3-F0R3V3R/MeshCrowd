'use strict';

// Assembles a self-contained "just copy this folder to another machine" distribution:
// runtime/node.exe copied in, all server+web source, vendored node_modules, empty data/ tree.
// Run from the project root with the current machine's Node already installed: `node scripts/build-portable.js`

const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');

const ROOT = path.join(__dirname, '..');
const DIST = path.join(ROOT, 'dist', 'dismesh-portable');

const INCLUDE = [
  'server', 'web', 'lang', 'electron', 'runtime', 'scripts', 'package.json',
  'start-server.bat', 'start-server.sh', 'setup-turn.bat', 'setup-turn.sh', 'start-client.bat', 'start-client.sh', 'README.md',
];
const EXCLUDE_FROM_NODE_MODULES = new Set(['.cache', '.bin']); // .bin has non-portable absolute shebangs, regenerated by npm anyway

function copyRecursive(src, dest, { skipTopNames } = {}) {
  const stat = fs.statSync(src);
  if (stat.isDirectory()) {
    fs.mkdirSync(dest, { recursive: true });
    for (const entry of fs.readdirSync(src)) {
      if (skipTopNames && skipTopNames.has(entry)) continue;
      copyRecursive(path.join(src, entry), path.join(dest, entry));
    }
  } else {
    fs.copyFileSync(src, dest);
  }
}

function main() {
  console.log('[build-portable] target:', DIST);
  fs.rmSync(DIST, { recursive: true, force: true });
  fs.mkdirSync(DIST, { recursive: true });

  for (const name of INCLUDE) {
    const src = path.join(ROOT, name);
    if (!fs.existsSync(src)) continue;
    copyRecursive(src, path.join(DIST, name));
  }

  // node_modules (production deps only — Electron, if present, is optional and huge; ship it
  // only if it's already installed, since it can't be downloaded from inside this build step).
  const nodeModulesSrc = path.join(ROOT, 'node_modules');
  if (fs.existsSync(nodeModulesSrc)) {
    copyRecursive(nodeModulesSrc, path.join(DIST, 'node_modules'), { skipTopNames: EXCLUDE_FROM_NODE_MODULES });
  }

  // Portable node.exe: copy from wherever the current `node` binary lives.
  const nodeExeSrc = process.execPath;
  const runtimeDir = path.join(DIST, 'runtime');
  fs.mkdirSync(runtimeDir, { recursive: true });
  if (os.platform() === 'win32') {
    fs.copyFileSync(nodeExeSrc, path.join(runtimeDir, 'node.exe'));
    console.log('[build-portable] bundled node.exe from', nodeExeSrc);
  } else {
    fs.copyFileSync(nodeExeSrc, path.join(runtimeDir, 'node'));
    fs.chmodSync(path.join(runtimeDir, 'node'), 0o755);
    console.log('[build-portable] bundled node binary from', nodeExeSrc);
  }

  // Empty data/ skeleton (never ship an existing DB/config — target host self-installs on first run).
  for (const sub of ['avatars', 'attachments', 'servericons', 'certs']) {
    fs.mkdirSync(path.join(DIST, 'data', sub), { recursive: true });
  }

  console.log('[build-portable] done. Copy the dist/dismesh-portable folder to the target machine,');
  console.log('[build-portable] edit data/config.json (created on first run) if the port/host needs to change, then run start-server.bat / start-server.sh.');
}

main();
