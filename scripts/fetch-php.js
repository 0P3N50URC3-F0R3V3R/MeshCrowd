'use strict';

// Downloads the portable PHP (Windows NTS x64) and Microsoft's Visual C++ redistributable into
// runtime/php/. Run once on the build machine: `npm run fetch:php [-- --branch=8.4]`.
// build-portable.js copies runtime/ wholesale, so the result ships with the portable build.

const fs = require('node:fs');
const path = require('node:path');
const https = require('node:https');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');

const OUT = path.join(__dirname, '..', 'runtime', 'php');
const BRANCH = ((process.argv.find((a) => a.startsWith('--branch=')) || '--branch=8.4').split('=')[1]);
const RELEASES_URL = 'https://windows.php.net/downloads/releases/releases.json';
const RELEASE_BASE = 'https://windows.php.net/downloads/releases/';
const VCREDIST_URL = 'https://aka.ms/vs/17/release/vc_redist.x64.exe';

function get(url, redirects = 5) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { 'user-agent': 'meshcrowd-fetch-php' } }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        res.resume();
        if (redirects <= 0) return reject(new Error('too many redirects'));
        return resolve(get(new URL(res.headers.location, url).href, redirects - 1));
      }
      if (res.statusCode !== 200) { res.resume(); return reject(new Error(`${url} -> HTTP ${res.statusCode}`)); }
      resolve(res);
    }).on('error', reject);
  });
}

async function fetchText(url) {
  const res = await get(url);
  const chunks = [];
  for await (const c of res) chunks.push(c);
  return Buffer.concat(chunks).toString('utf8');
}

async function download(url, dest) {
  const res = await get(url);
  await new Promise((resolve, reject) => {
    const f = fs.createWriteStream(dest);
    res.pipe(f);
    f.on('finish', resolve);
    f.on('error', reject);
    res.on('error', reject);
  });
}

const sha256 = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');

function ps(command, env) {
  const r = spawnSync('powershell', ['-NoProfile', '-NonInteractive', '-Command', command], { stdio: 'inherit', env: { ...process.env, ...env } });
  if (r.status !== 0) throw new Error(`powershell failed (${r.status}): ${command}`);
}

const PHP_INI = `; Generated by scripts/fetch-php.js. Per-process hardening is applied on the command line (see server/lib/phpRuntime.js).
extension=mbstring
short_open_tag=Off
date.timezone=UTC
default_charset=UTF-8
`;

async function main() {
  if (process.platform !== 'win32') {
    console.log('[fetch-php] The bundled PHP is Windows-only. On this OS install php with your package manager or set "sites.phpPath" in data/config.json.');
    return;
  }
  fs.mkdirSync(OUT, { recursive: true });

  const releases = JSON.parse(await fetchText(RELEASES_URL));
  const rel = releases[BRANCH];
  if (!rel) throw new Error(`PHP branch ${BRANCH} not found; available: ${Object.keys(releases).join(', ')}`);
  const build = rel['nts-vs17-x64'] || rel['nts-vs16-x64'];
  if (!build) throw new Error(`no NTS x64 build for ${BRANCH}`);

  const zipPath = path.join(OUT, build.zip.path);
  console.log(`[fetch-php] downloading PHP ${rel.version} (${build.zip.path})`);
  await download(RELEASE_BASE + build.zip.path, zipPath);
  if (sha256(zipPath).toLowerCase() !== String(build.zip.sha256).toLowerCase()) {
    fs.rmSync(zipPath, { force: true });
    throw new Error('PHP zip checksum mismatch; download discarded');
  }
  ps('Expand-Archive -LiteralPath $env:PHP_ZIP -DestinationPath $env:PHP_OUT -Force', { PHP_ZIP: zipPath, PHP_OUT: OUT });
  fs.rmSync(zipPath, { force: true });
  fs.writeFileSync(path.join(OUT, 'php.ini'), PHP_INI);
  fs.writeFileSync(path.join(OUT, 'VERSION.txt'), `${rel.version}\n`);

  const vcPath = path.join(OUT, 'vc_redist.x64.exe');
  console.log('[fetch-php] downloading the Visual C++ redistributable');
  await download(VCREDIST_URL, vcPath);
  ps("$s = Get-AuthenticodeSignature -LiteralPath $env:VC_EXE; if ($s.Status -ne 'Valid' -or $s.SignerCertificate.Subject -notmatch 'Microsoft') { exit 1 }", { VC_EXE: vcPath });

  console.log(`[fetch-php] done: ${path.join(OUT, 'php.exe')}`);
}

main().catch((err) => { console.error('[fetch-php] failed:', err.message); process.exit(1); });
